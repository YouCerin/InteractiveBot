/** 可选的人格预设。id → 文本。 */
export const PERSONA_PRESETS = {
  /** 推荐默认：语气细节更足，token 仍可控。 */
  mermaid: FULL,
  /** 精简版：预算紧张时用。 */
  'mermaid-lite': LITE,
  /** 不要人设，只用平台规则（用于排查"是不是人设的锅"）。 */
  none: '',
}

/** 默认预设。 */
export const DEFAULT_PERSONA_PRESET = 'mermaid'

/**
 * 取人设文本。
 *
 * 优先级：**自定义文本 > 预设**。
 * 这样用户既可以用我调好的预设，也可以完全自己写。
 *
 * @param {{ preset?: string, custom?: string }} [opts]
 * @returns {string} 人设文本（可能是空串，表示不使用人设）
 */
export function buildPersona({ preset, custom } = {}) {
  // 自己写了就用自己写的 —— 自定义永远优先，这样不会被预设"覆盖"
  if (typeof custom === 'string' && custom.trim()) return custom.trim()

  const id = preset || DEFAULT_PERSONA_PRESET
  if (Object.prototype.hasOwnProperty.call(PERSONA_PRESETS, id)) {
    return PERSONA_PRESETS[id]
  }
  // 预设名写错时**不要静默回落**：那会让人以为自定义生效了。
  // 抛错由调用方决定怎么处理（配置校验阶段会拦下）。
  throw new Error(
    `未知的人设预设「${id}」。可选：${Object.keys(PERSONA_PRESETS).join(' / ')}；` +
      `或直接用 persona.custom 写你自己的。`,
  )
}

/**
 * 校验人设配置（供配置自检调用）。
 * @returns {string[]} 问题列表（空 = 没问题）
 */
export function lintPersona({ preset, custom } = {}) {
  const problems = []
  if (typeof custom === 'string' && custom.trim()) {
    // 阈值定在 8 字，而不是 20。
    // 第一版写 20，结果「你是一个爱吐槽的群友，说话要短。」（中文 17 字）
    // 这种**完全有效**的人设被判成"太短" —— 测试当场抓出来了。
    // 中文信息密度高，用英文的字数直觉定阈值不合适。这里只为拦住
    // "随手写了两个字"这种明显误操作，不做质量评判。
    if (custom.trim().length < 8) {
      problems.push(`persona.custom 太短了（只有 ${custom.trim().length} 字），可能写错了`)
    }
    // 人设里提到不存在的工具会诱发幻觉调用 —— 这是我们踩过的坑，主动检查。
    //
    // ⚠️ 这个检查我写错了两次，两次都被测试抓出来，记在这里免得后人再踩：
    //   坑 1：用 `\b([a-z_]{3,30})\s*\(`，以为工具名后面会跟括号。
    //         但 `\b` 在**中文字符旁边也会成立**（中文属 \W、英文属 \w，
    //         交界处就是词边界），于是「请用 set_member_note 记录」被截成
    //         `et_member_note` —— 既漏报又报了个错名字。
    //   坑 2：改用 lookbehind 修正词首之后，仍然要求后面跟 `(`。
    //         可实际写法里工具名**大多不带括号**（「用 web_search 查」），
    //         于是正常文本匹配不到、该报的也报不出来，测试直接失败。
    //
    // 现在的规则：**长得像工具标识符的词**（小写字母开头 + 含下划线）一律检查，
    // 不要求任何后缀。误报代价远小于漏报 —— 漏报会变成幻觉调用。
    const knownTools = [
      'read', 'write', 'edit', 'bash', 'pwsh', 'web_search', 'web_fetch',
      'todo_write', 'subagent', 'goal', 'skill', 'grep', 'glob', 'present',
      'ask_user_question', 'create_goal', 'update_goal', 'get_goal',
    ]
    const mentioned = [
      ...String(custom).matchAll(/(?<![A-Za-z0-9_])([a-z][a-z0-9]*_[a-z0-9_]*)/g),
    ].map((m) => m[1])
    const suspicious = mentioned.filter((name) => !knownTools.includes(name))
    if (suspicious.length) {
      problems.push(
        `persona.custom 里提到了可能不存在的工具：${[...new Set(suspicious)].join(', ')}。` +
          `提示词里提到不存在的工具会诱发幻觉调用，建议删掉或改成自然语言描述。`,
      )
    }
  } else if (preset && !Object.prototype.hasOwnProperty.call(PERSONA_PRESETS, preset)) {
    problems.push(`persona.preset「${preset}」不存在。可选：${Object.keys(PERSONA_PRESETS).join(' / ')}`)
  }
  return problems
}
