/**
 * **机器人自述**：它讲"自己这边会怎样"的那些话。
 *
 * ══════════════════════════════════════════════════════════════════════════
 * 为什么单独一类（用户 2026-10-01 点名：简化 + 降权）
 * ══════════════════════════════════════════════════════════════════════════
 * 真机上真实落过这样一条（个人档里）：
 *
 *     （我许的诺）往外写、改、删，或者跑那种会落到工作区外面的操作，都会被挡下来 ——
 *     这种时候我会直接跟你说一句"这个我暂时没权限"，不会硬试
 *
 * 问题不在"记错了"，而在**它被当成一条记忆反复注入**：
 *   ① 那是**机器人在解释自己**，不是关于对方的任何事实 ——
 *      个人的档案里塞进一段"我这边如何如何"，将来读起来像一句无主的自述；
 *   ② 系统边界**每轮都在提示词里**（平台规则那一段），根本不需要"记"；
 *   ③ 它还是**第一人称**：与档案里其他条目的隐含主语（他）冲突。
 * 用户给的处理是「**简化，权重也变低**」——所以这里不删，而是：
 *   · **写入侧**：模型提议这类内容时**只在回执里拦一次**（告诉它不用记，边界是代码的事）；
 *   · **读取侧**：已经落盘的那些在注入时**压成一行短标签**（不再逐字注入）。
 *
 * ⚠️ 判据**两段式**（与 `thirdPartyNegative` 同一条思路）：
 *   只看"我"会把「他说我上次答应的事没做」这种**关于对方**的条目误杀；
 *   只看边界词会把「他工作内容要依靠电脑」这种无关条目误杀（那里面没有边界词，安全）。
 *   所以要求：**第一人称机器人主语** 且 **谈到自己的能力/边界**，两者同时出现。
 */

/**
 * 机器人在说"我这边/我们这边"（第一人称 + 机器人视角）。
 *
 * ⚠️ 用**两段式**（第一人称标记 + 边界词）而不是一串手写枚举：枚举永远会漏
 *   （"我没有权限删文件"里"我"后面直接跟"没权限"，任何枚举都没命中 —— 实测踩过）。
 *   放宽之后"他说我上次答应的事没做"这类**关于对方的**条目仍然安全：
 *   它一个边界词都没有。
 */
const SELF_SUBJECT_RE = /(我这边|我们这边|我手上|我的能力|我的权限|我的工作区|我)/

/** 谈的是**能力/边界/机制**（而不是情绪、偏好、承诺）。任一条命中即可。 */
const SELF_BOUNDARY_PATTERNS = [
  // ① 明确的"我做不到/我没权限"
  /(没(有)?权限|权限不够|做不了|不能做|不能(动手|操作)|不会被放行)/,
  // ② 系统机制词：越界 / 沙箱 / 工作区外 / 审批 / 拦截 / 报错
  /(越界|沙箱|工作区外|工作区外面|需要审批|走审批|被(系统)?(拒绝|拦截|驳回)|审批|报错)/,
  // ③ 能力范围：只读 / 只能看聊 / 只允许
  /(只读|只(能|会)(看|聊|说|查|读|回答)|只允许)/,
  // ④ "会被挡下来"这类被动处置
  /(会被挡|被挡下来|会被拦)/,
  // ⑤ 不主动（插话/搭话）
  /不主动/,
]

/**
 * 这条记忆是不是**机器人在自述**？
 *
 * 判据 = **第一人称** 且 **谈到能力/边界/机制**，两者同时出现。
 *
 * @param {string} text 记忆正文（已剥掉 `<<<MEMORY …>>>` 与档位）
 * @returns {{hit: boolean, why?: string}}
 */
export function isBotSelfEntry(text) {
  const t = String(text ?? '').trim()
  if (!t) return { hit: false }
  if (!SELF_SUBJECT_RE.test(t)) return { hit: false }
  if (!SELF_BOUNDARY_PATTERNS.some((re) => re.test(t))) return { hit: false }
  return { hit: true, why: '这是机器人在讲自己（能力/边界），不是关于对方的记忆' }
}

/**
 * 注入时把自述压成**一行短标签**（用户要求：简化 + 降权）。
 *
 * ★ 刻意**不做语义摘要**：规则层做摘要只会造出半截句子。
 *   这里只做三件事：换个不冒充事实的说法、**标明它不必当真**、截断。
 *   （真想让它变成一句好话，那是模型该在**写入时**做的事 —— 写法指引里已写明。）
 *
 * ★ 前缀为什么写「说话时的说法，不必当真」而不是「我的自述」：
 *   用户要的是**降权**。而这一行与平台规则里那段权威的边界说明**可能不一致**
 *   （那是它当时随口的一种说法），所以必须让将来的自己知道：**边界以平台规则为准**。
 *
 * @param {string} text
 * @param {number} [max] 正文上限（默认 40 字，不含前缀）
 */
export function compactSelfEntry(text, max = 40) {
  const t = String(text ?? '')
    .replace(/^（(我许的诺|对方许的诺)）/, '')
    .replace(/^（[^）]*）/, '')
    .replace(/\s+/g, ' ')
    .trim()
  const body = t.length > max ? `${t.slice(0, max)}…` : t
  return `（我说话时的一种说法，不必当真）${body}`
}
