/**
 * 按说话方式拼装这一轮的人设文本。
 *
 * ── 两条路（**哪条路要能被日志看见**）──────────────────────────────────
 *   · `replace`：人设分得出节，且其中有"口吻节" ⇒ 换掉那几节（其余逐字保留）；
 *   · `append` ：分不出节、或**没有口吻节**（例如整篇散文） ⇒ 追加在末尾。
 *     ⚠️ 追加有已知代价：原人设里与 `VOICE_STYLE` 冲突的句子**还在**（模型要自己取舍），
 *     所以调用方会把 `strategy` 记进日志，让"这套人设没被真正换掉"看得见。
 *
 * ★ 与 0.3.0beta 的 `composePersonaForModeDetailed` 的关系：那个函数在 `mode !== 'chat'`
 *   时**逐字返回人设**（那是"工作态 = 升级前行为"的实现）。现在没有第二个态了，
 *   所以**没有那个提前返回** —— 这条路径上唯一的开关是"有没有一份说话方式"。
 *
 * @param {object} opts
 * @param {string} opts.personaText 基座人设（构造期解析出来的那一份）
 * @param {string} [opts.style] 说话方式文本（空 = 不做任何替换，**逐字返回人设**）
 * @returns {{text: string, strategy: 'none'|'replace'|'append', replaced: string[]}}
 */
export function composeVoice({ personaText = '', style = VOICE_STYLE } = {}) {
  const base = String(personaText ?? '')
  const voice = String(style ?? '').trim()
  // 说话方式为空（被显式传空）⇒ 一个字都不改，并让调用方去日志里说清。
  // 宁可用老腔调，也不要把人设拆一半 —— 拆一半的结果是既没新风格又丢了旧约束。
  if (!voice) return { text: base, strategy: 'none', replaced: [] }
  if (!base.trim()) return { text: voice, strategy: 'replace', replaced: [] }

  const { pre, sections } = splitPersonaSections(base)
  if (sections.length === 0) {
    // 人设没有分节（用户自己写的一整段）⇒ **追加**而不是替换：
    // 我们没有"哪一节是口吻"这个信息，猜着删会删掉别的东西。
    return { text: `${base.replace(/\s+$/, '')}\n\n${voice}`, strategy: 'append', replaced: [] }
  }

  // ★ 用**规范名**判断（认别名：`二、怎么说话` 与 `【怎么说话】` 是同一节）
  const replaced = []
  const kept = sections.filter((s) => {
    const canon = canonicalStyleSection(s.title)
    if (STYLE_SECTIONS.includes(canon)) {
      replaced.push(s.title)
      return false
    }
    return true
  })
  // ① 一节都没换掉 ⇒ 这套人设里没有"口吻节"，追加是唯一能做的事（但要能被日志看见）
  if (replaced.length === 0) {
    return { text: `${base.replace(/\s+$/, '')}\n\n${voice}`, strategy: 'append', replaced: [] }
  }
  const out = renderPersonaSections({ pre, sections: kept })
  // ② 全被换光了（人设只有口吻节）⇒ 结果就是说话方式本身
  if (kept.length === 0 && !String(pre).trim()) {
    return { text: voice, strategy: 'replace', replaced }
  }
  return { text: `${out.replace(/\s+$/, '')}\n\n${voice}`, strategy: 'replace', replaced }
}

/**
 * 只要文本的便捷包装。
 * @returns {string}
 */
export function composeVoiceText(opts = {}) {
  return composeVoice(opts).text
}
