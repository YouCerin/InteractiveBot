/**
 * **说话方式（唯一口径）**：融合了 0.3.0beta 的「闲聊态」口吻与工作态的人设基座。
 *
 * ══════════════════════════════════════════════════════════════════════════
 * 它解决什么问题（用户原话）
 * ══════════════════════════════════════════════════════════════════════════
 * 「目前的对话太像 AI」—— 即使人设里已经写了"短、不用 Markdown、别当客服"，
 * 回出来的东西仍然是助手腔。0.3.0beta 的做法是**按消息分两态**：闲聊时换成
 * 一份 `styles/闲聊.md` 的口吻，干活时维持老说法（"工作态 = 升级前的行为"
 * 是那一版的安全边界，`mocks/fixtures/prompt-golden.txt` 逐字钉着它）。
 *
 * 0.3.0alpha 把那条分界线**拆掉**了：说话方式只有一份，所有回合都用它 ——
 * 包括真的在干活的时候。理由（用户 2026-10-02 的决定）：
 *   · 「像不像 AI」不是闲聊才有的问题：干活时那句「好的，我来帮你……」同样是助手腔；
 *   · 分两态等于**同一份提示词里两处对同一件事给相反指令** ——
 *     基座的「认真问技术问题就认真答」对上闲聊的「别把回答扩成一段」，
 *     模型只能自己挑一套听，结果两个方向都不稳定；
 *   · 判定本身还有成本（一次小模型调用）与一类失败（判错口径）。
 *
 * ══════════════════════════════════════════════════════════════════════════
 * 融合的**唯一硬约束**：不许留下两套相反指令
 * ══════════════════════════════════════════════════════════════════════════
 * 原来那两句冲突的话是：
 *   · 基座 `【别变成客服】`：「**但对方认真问事实、技术问题时，就认真答**」
 *   · 闲聊 `styles/闲聊.md`：「**极短。一句话能说完就一句话**」「**别把一句回答扩成一段**」
 * 融合后的口径是**默认极短 + 真在干活时允许说清**（`WORK_ALLOWANCE`），而不是把
 * 两句都留下 —— 留下一对相反指令就是这次改动要消灭的东西本身。
 *
 * ⚠️ 底下那份 `VOICE_STYLE` 里**逐字保留了使用者给过的规则与例句**（接梗三例、
 *    摆资历、情色暗示、别自贬、别抖记忆…）。它们不是"文案"，是**判据的一部分**：
 *    `mocks/verify-voice-style.mjs` 有断言逐条钉着，别在"精简提示词"时顺手删掉。
 *    要改判据就**同时改断言**，并在断言旁写清旧写法为什么错。
 *
 * ══════════════════════════════════════════════════════════════════════════
 * 放在**代码**里而不是 `styles/*.md` 文件里（0.3.0alpha 的改动之一）
 * ══════════════════════════════════════════════════════════════════════════
 * `styles/` 目录**从来没有进过发布包**（`scripts/assemble-release.mjs` 的
 * `COPY_DIRS` 里没有它），所以线上一直跑的就是这份内置常量，文件只是开发期的
 * 一份镜像 —— 而那份镜像带来过真实的代价：两份文本会漂（`chat-style-sync.mjs`
 * 就是为同步它而写的）、配置里多一个"用哪份风格"的开关、评审台还得跟着解析
 * 文件路径（其中"空名字拼出 `<styles>/.md`"是一个踩过的坑）。
 * 融合之后只剩一份口径，以上全部不再需要。
 */

