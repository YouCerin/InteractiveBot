/**
 * 记忆文本的**比较**工具：归一化 + 字符 bigram 相似度。
 *
 * ══════════════════════════════════════════════════════════════════════════
 * 为什么要单独一个模块（而不是留在 memory-consolidate.mjs 里）
 * ══════════════════════════════════════════════════════════════════════════
 * 这两样东西现在有**两个**消费者，而且它们不该互相依赖：
 *   · `memory-consolidate.mjs` —— 整理时判"两条是不是同一条"（合并）
 *   · `memory-store.mjs`      —— 写入时判"这条是不是在更正上面某条"（H4 supersede）
 * 如果放在整理模块里，"写入"就要依赖"整理"，而整理又（为了列文件）依赖写入 ——
 * **一个循环依赖**。ESM 能容忍它，但那种容忍是"跑起来没事、改一行就炸"，
 * 这个项目已经因为"看不见的接线错误"付过代价（见 `AGENT.md` 第 9 条）。
 * 所以把纯文本度量抽出来，拍平依赖：**谁都不依赖谁，大家一起依赖它**。
 *
 * 这里**只有纯函数**：不碰文件、不碰配置、可离线测。
 */

/** 行首冗余的日期前缀：`2026-09-26 ` / `2026-09-26：` / `[2026-09-26] `。 */
export const LEADING_DATE_RE = /^\[?\d{4}[-/年]\d{1,2}[-/月]\d{1,2}日?\]?\s*[：:，,]?\s*/

/**
 * 行首的"转述前缀"：`他说` / `据他说，` / `他提到` / `他指出`。
 *
 * ══════════════════════════════════════════════════════════════════════════
 * 为什么可以安全摘掉（这条规则只在"按人分档的档案里"成立）
 * ══════════════════════════════════════════════════════════════════════════
 * `memory/private-<QQ>.md` 这个文件**本身就是"关于这个人的档案"** ——
 * 里面每一条的隐含主语永远是他。所以"他说""据他说"**不携带任何信息**，
 * 是纯粹的噪音；实测模型写得非常多（`据他说,他每天玩 DSH…`）。
 *
 * ⚠️ 两条刻意的限制，别放宽：
 *   ① **只处理行首**。句中的"他说"可能是有意义的区分
 *      （例如"张三说他不行"里的转述方是别人）。
 *   ② **不处理"我"开头的转述**（`我提醒…` / `我指出…` / `我判断…`）。
 *      那类要判断"整条是不是只有模型的自述"，属于**语义判断**，
 *      交给 LLM 版（二期）。规则版硬做会误删内容。
 */
export const LEADING_ATTRIBUTION_RE =
  /^(据他(说|提到|讲|表示)|他(说|提到|讲到|表示|指出|认为|补充|强调|希望|想让|想要|要让))\s*[，,：:]?\s*/

/**
 * 归一化一条记忆正文（用于**比较**，不用于写回）。
 *
 * 把标点、空白、日期前缀、转述前缀都抹掉之后，剩下的才是"这条到底说了什么"。
 */
export function normalizeForCompare(text) {
  return String(text ?? '')
    .replace(LEADING_DATE_RE, '')
    .replace(LEADING_ATTRIBUTION_RE, '')
    .replace(/[\s\u3000]+/g, '')
    .replace(/[，,。.；;：:！!？?、"'""''（）()\[\]【】《》<>~～\-—_/\\|]/g, '')
    .toLowerCase()
}

/** 字符 bigram 集合（中文短文本相似度用，不需要分词）。 */
export function bigrams(s) {
  const out = new Set()
  const t = String(s ?? '')
  if (t.length === 0) return out
  if (t.length === 1) {
    out.add(t)
    return out
  }
  for (let i = 0; i + 1 < t.length; i += 1) out.add(t.slice(i, i + 2))
  return out
}

/**
 * 两条记忆的相似度：归一化后的字符 bigram Jaccard。
 *
 * 为什么不用编辑距离：中文改几个字（"他说的"→"据他说"）编辑距离不小，
 * 但语义完全一样；bigram 集合对这类改写更宽容。
 *
 * @returns {number} 0~1
 */
export function similarity(a, b) {
  const A = bigrams(normalizeForCompare(a))
  const B = bigrams(normalizeForCompare(b))
  if (A.size === 0 && B.size === 0) return 1
  if (A.size === 0 || B.size === 0) return 0
  let inter = 0
  for (const g of A) if (B.has(g)) inter += 1
  return inter / (A.size + B.size - inter)
}
