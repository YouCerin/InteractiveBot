/**
 * 技能「表情包」的入口。
 *
 * ══════════════════════════════════════════════════════════════════════════
 * 这个技能与别的技能最不一样的地方：**它没有工具**
 * ══════════════════════════════════════════════════════════════════════════
 * pixiv 那类技能是"给模型加一个工具，模型去调"。表情包不是 —— 恰恰相反，
 * 本项目的立场是**不让模型去挑图**：
 *   · `persona.mjs:20` 记着一条真实教训：源项目的人设里引用了 `list_stickers`
 *     等**并不存在的工具**，于是模型学会了幻觉调用；
 *   · 而"挑哪张图"是本地打分能做得更好、更便宜、更可解释的事（运行期零 token）。
 *
 * 所以这里的形态是：
 *   · **提示词段**（`promptSections`）：告诉模型"可以写 `[sticker:标签]`"，
 *     且**只列库里真有货的标签**（清单由宿主按当前库现算后传进来）；
 *   · **没有工具、也没有决策钩子** —— 判定在宿主侧（理由见文件末尾那一段）。
 *
 * ══════════════════════════════════════════════════════════════════════════
 * 这个目录里什么是"技能"，什么是"宿主的引擎"
 * ══════════════════════════════════════════════════════════════════════════
 *   本目录（可整目录拷走）：**只有清单 + 设置 + 说明**（`skill.json` / `README.md`
 *                           + 本文件），零依赖、零 import，搬到哪里都能被加载
 *   宿主 `src/`：库读写、四层判定、配额台账（`sticker-library/decision/quota.mjs`）、
 *              以及**离线导入与打标签的脚本**（`src/sticker-import.mjs`、
 *              `src/sticker-tag.mjs`）—— 它们要读写库与调模型，所以不在本目录
 *
 * ★ 别把"可整目录拷走"读成"这个目录自带全部功能"：本目录是**清单层**，
 *   真正干活的东西在宿主（这也是下面"为什么没有决策钩子"那段的同一个边界）。
 *   实测踩过：本文件原来写成"本目录含离线导入/打标签脚本"，而目录里根本没有 ——
 *   照着文档拷走会得到一个**没有脚本的技能**。现在有断言盯着这个说法（见
 *   `mocks/verify-sticker-skill.mjs` 第 ⑥ 节）。
 *
 * 判据很简单：**需要碰桥接状态机的，就不在技能里**。这样"发错图"这条最贵的
 * 失败路径始终在宿主自己的测试覆盖面之内（`npm run test:sticker`）。
 */

/**
 * 工具：一个都不注册。
 *
 * ★ 刻意留空而不是"顺手加个 list_stickers"：模型能自己挑图 = 幻觉风险
 *   （它没有库的图像，只能凭标签名猜），而且会绕过本地的频率与阈值约束。
 */
export function setup() {}

/**
 * 能力自检（**必须同步**；宿主在控制台点「自检」时调）。
 *
 * 只说"有没有、够不够"，**不判网络、不读大文件** —— 同步函数里做 IO
 * 会让控制台卡住（规范 §3.1）。
 */
export function available(context = {}) {
  const settings = context?.settings ?? context?.config?.skills?.sticker ?? {}
  if (settings.enabled === false) return { ok: false, reason: '技能自己是关着的' }
  return { ok: true }
}

/**
 * 提示词段。
 *
 * ⚠️ **不在这里现算标签清单**：那要读库、还要知道"哪些标签真有货"，
 *    而 `promptSections` 按契约必须是**纯函数**（无 IO、每轮都调）。
 *    所以宿主会把现算好的行传进来（`context.stickerLines`）；
 *    没有就返回空数组 —— **一个字都不写**，绝不承诺做不到的事。
 */
export function promptSections(context = {}) {
  const lines = Array.isArray(context?.stickerLines) ? context.stickerLines.filter(Boolean) : []
  if (!lines.length) return []
  return [{ id: 'sticker', title: '表情包', priority: 60, content: lines.join('\n') }]
}

/**
 * ── 这个技能**没有**决策钩子，这是刻意的（不是漏了）──────────────────────
 *
 * 你可能会想："自主发表情这么核心的事，怎么不放在技能里？"
 * 答案是**边界**：
 *
 *   · 技能的契约要求"不要 import 宿主内部模块、能整目录拷走"（规范 §12.3）；
 *     而"发不发"的判定要用到**配额台账、隐私/投递闸门的顺序、拟人延迟、
 *     发送失败的冷却** —— 那些是桥接的状态机，不是外部能力包该碰的东西。
 *   · 判定必须是**纯函数 + 可离线单测**的（`src/sticker-decision.mjs` 有 83 项断言）。
 *     把它塞进技能目录等于让"发错图"这条最贵的失败路径离开宿主的测试覆盖面。
 *
 * 所以本项目把这件事拆成两层：
 *   ① 宿主侧（`src/sticker-*.mjs`：库 / 判定 / 配额 / 离线导入与打标签）—— 引擎，可单测；
 *   ② 技能目录（本目录）—— **清单 + 设置 + 说明**，零依赖，可整目录搬走。
 * 这也是本项目对"表情包该不该做成技能"的最终答案：**功能是技能，
 * 判定必须在宿主**（理由写在 `docs/插件设计规范.md` §7 末尾）。
 */
